describe("the practice's own terms are no language", () => {
  const knownTerms = [
    "Zelora Glow Facial",
    "Kaviar Peel",
    "Dr. Ngozi Okafor",
    "75-5660 Palani Rd, Kailua-Kona, HI",
    "Glow Med Spa",
  ];

  test.each(["zelora glow + kaviar peel?", "ngozi okafor?", "kailua kona?", "zelora?"])(
    "%j is turned away without them, and read as English with them",
    (text) => {
      expect(messageLanguage(text)).toBe("other");
      expect(messageLanguage(text, { knownTerms })).toBe("en");
    },
  );

  test("they never make another language English", () => {
    expect(messageLanguage("Mwen pa ka respire, Kaviar Peel", { knownTerms })).toBe("other");
    expect(messageLanguage("Je n'arrive pas à respirer après le Zelora", { knownTerms })).toBe(
      "other",
    );
  });

  test("treatment, brand and device names are neutral without being told", () => {
    for (const text of [
      "daxxify",
      "NAD+ infusion",
      "emsculpt neo",
      "ultherapy vs thermage",
      "morpheus8",
      "glo2facial",
    ]) {
      expect(messageLanguage(text), text).toBe("en");
    }
  });
});
