-- =============================================================================
-- The retention clock for a signed business associate agreement.
--
-- 45 CFR 164.530(j)(2) requires the documentation to be retained six years
-- "from the date of its creation or the date when it last was in effect,
-- whichever is later." 164.316(b)(2)(i) says the same thing for the security
-- rule's documentation. For a BAA, "last in effect" is TERMINATION — so the
-- clock is greatest(accepted_at, terminated_at) + 6 years, and a clinic that
-- stays three years owes nine years from the day they signed.
--
-- Computing retention from accepted_at alone is the classic error. It is not a
-- rounding error: it marks agreements that are still in force as expired, and
-- the first thing anyone does with an "expired" record is destroy it.
--
-- Three facts are recorded here, and a fourth is derived from them:
--
--   terminated_at          when the agreement stopped being in effect
--   copy_sent_at           when the counterparty's copy was delivered
--   copy_document_sha256   the hash of the exact PDF they received
--   retention_eligible_at  GENERATED — the six-year floor
--
-- ## Why the clock is a generated column
--
-- Because a retention date that some code path can write is a retention date
-- somebody can set to a convenient value, and the convenient value is always
-- "earlier". GENERATED ALWAYS ... STORED means there is no INSERT and no UPDATE
-- — from the runtime role, the migrator, psql, or a service written next year
-- — that can move it. It is a function of accepted_at and terminated_at, or it
-- does not exist. The alternative, computing it in application code at read
-- time, was rejected for the obvious reason: two readers, two answers.
--
-- ## Why nothing here deletes, and never will
--
-- Six years is a FLOOR, not a schedule. This system records the dates, computes
-- when a row BECOMES ELIGIBLE for review, and shows that to a human. It does
-- not sweep, expire, or purge. The runtime role has no DELETE on this table
-- (0006) and does not get one here; purging is a deliberate act by a person
-- holding the migrator role, on a row this table can prove is eligible. A
-- background job that destroys evidence on a timer is a liability with a cron
-- entry.
--
-- Note also what "eligible" does NOT mean. While terminated_at is null the
-- generated value is computed from creation alone, because the real end of a
-- live agreement's clock is not yet knowable. A live agreement is never
-- eligible for anything, however old it is — see lib/agreements/retention.ts,
-- which refuses to say otherwise.
-- =============================================================================

ALTER TABLE "baa_acceptances" ADD COLUMN "terminated_at" timestamp with time zone;--> statement-breakpoint
ALTER TABLE "baa_acceptances" ADD COLUMN "copy_sent_at" timestamp with time zone;--> statement-breakpoint
ALTER TABLE "baa_acceptances" ADD COLUMN "copy_document_sha256" text;--> statement-breakpoint

-- The six years are added IN UTC, and that is not a stylistic choice.
--
-- `timestamptz + interval` is STABLE, not immutable: adding months or years
-- depends on the session's TimeZone setting. Postgres refuses a non-immutable
-- generation expression outright, so the naive form does not merely drift over
-- a DST boundary — it will not create the column at all. Converting to UTC,
-- adding there, and converting back uses only immutable functions and gives one
-- deterministic answer regardless of who is connected from where.
--
-- GREATEST already ignores NULLs in Postgres, so the COALESCE is redundant to
-- the engine and load-bearing for the reader: it says out loud that an
-- agreement still in effect falls back to its own creation date.
ALTER TABLE "baa_acceptances" ADD COLUMN "retention_eligible_at" timestamp with time zone GENERATED ALWAYS AS ((((greatest(accepted_at, coalesce(terminated_at, accepted_at)) at time zone 'UTC') + interval '6 years') at time zone 'UTC')) STORED NOT NULL;--> statement-breakpoint

COMMENT ON COLUMN baa_acceptances.retention_eligible_at IS
  '45 CFR 164.530(j)(2): retain six years from creation or from the date the agreement last was in effect, whichever is later — hence greatest(accepted_at, terminated_at) + 6 years. This is a FLOOR, not a deletion schedule and not an instruction: nothing in this system deletes a BAA, and while terminated_at is null the value is computed from creation alone and says nothing about when a live agreement may be destroyed. Generated by the database so it cannot be set to a convenient value.';
--> statement-breakpoint

COMMENT ON COLUMN baa_acceptances.terminated_at IS
  'When the agreement stopped being in effect. Null while it still is. Write-once (see the transition guard below): moving or clearing it moves the retention clock.';
--> statement-breakpoint

COMMENT ON COLUMN baa_acceptances.copy_sent_at IS
  'When the counterparty was sent their own copy of what they signed. A contract whose other party cannot produce a copy is a bad position; this records that they can.';
--> statement-breakpoint

COMMENT ON COLUMN baa_acceptances.copy_document_sha256 IS
  'SHA-256 of the exact PDF delivered — not of rendered_text. The two agree in content, but the artefact the clinic holds is the PDF, and "what did they actually receive" is the question a dispute asks.';
--> statement-breakpoint

-- Only a terminated agreement can ever become eligible, so the index carries
-- that rule rather than leaving it to whoever writes the next query.
CREATE INDEX "baa_acceptances_retention_idx" ON "baa_acceptances" USING btree ("retention_eligible_at") WHERE "baa_acceptances"."terminated_at" is not null;--> statement-breakpoint

-- Termination before signature is not a late correction, it is a corrupt row —
-- and it would drag the retention floor backwards to accepted_at + 6 years.
ALTER TABLE "baa_acceptances" ADD CONSTRAINT "baa_acceptances_terminated_after_accepted" CHECK ("baa_acceptances"."terminated_at" is null or "baa_acceptances"."terminated_at" >= "baa_acceptances"."accepted_at");--> statement-breakpoint

-- A delivery date with no hash proves nothing about what was delivered, and a
-- hash with no date is unanchored in time. Neither half is evidence alone.
ALTER TABLE "baa_acceptances" ADD CONSTRAINT "baa_acceptances_copy_evidence_complete" CHECK (("baa_acceptances"."copy_sent_at" is null) = ("baa_acceptances"."copy_document_sha256" is null));--> statement-breakpoint

ALTER TABLE "baa_acceptances" ADD CONSTRAINT "baa_acceptances_copy_hash_format" CHECK ("baa_acceptances"."copy_document_sha256" is null or "baa_acceptances"."copy_document_sha256" ~ '^[0-9a-f]{64}$');--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- Grants: three more columns, and not one more verb.
--
-- 0006 revoked UPDATE and DELETE outright. 0016 granted back UPDATE on
-- (organization_id, bound_at) so a signed agreement could be bound to the
-- organization it was signed for. This adds exactly the three columns above,
-- column-scoped in the same style and for the same reason: recording that the
-- agreement ended, or that we sent them their copy, is a legitimate write;
-- editing what they signed is not, and must remain physically impossible
-- rather than merely against the rules.
--
-- The posture this leaves, asserted in the DO block at the foot of this file:
--
--   healdesk_app UPDATE  organization_id, bound_at, terminated_at,
--                        copy_sent_at, copy_document_sha256   — and nothing else
--   healdesk_app DELETE  none, on this table, ever
--
-- rendered_text, document_hash, variables, assent_label, accepted_by_*,
-- ip_address, user_agent and accepted_at stay immutable BY GRANT, so the
-- guarantee survives a bug in our own code. retention_eligible_at is generated
-- and therefore writable by nobody at all.
-- ---------------------------------------------------------------------------
GRANT UPDATE (terminated_at, copy_sent_at, copy_document_sha256) ON baa_acceptances TO healdesk_app;
--> statement-breakpoint

-- Idempotent re-assertion, not a change. It costs nothing and it means the file
-- that adds writable columns is also the file that says, in executable form,
-- that the runtime role still cannot destroy this record.
REVOKE DELETE ON baa_acceptances FROM healdesk_app;
--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- The transition guard.
--
-- A column grant can say WHICH columns a role may write. It cannot say which
-- TRANSITIONS are legal, because it never sees the old row. Three things need
-- that distinction:
--
--   1. The audit found that 0016's grant lets any session holding the runtime
--      role rebind an acceptance that already belongs to another organization
--      — moving a signed contract to a different practice with one UPDATE.
--      The application's `where organization_id is null` prevents it; the
--      database did not.
--   2. Clearing terminated_at reverts the retention floor from
--      termination + 6y to signature + 6y, which can make a row that must be
--      kept for years look eligible for review today. The column grant above
--      is what makes that write reachable at all, so the guard against it
--      belongs in the same migration that opens the column — not in a later
--      one written after somebody notices.
--   3. Overwriting copy_document_sha256 replaces the record of what the
--      counterparty received with a claim about a different document.
--
-- So: binding is one-way and one-time, and each recorded fact is write-once.
-- Setting a value where there was none is allowed; changing or clearing one is
-- not. Every re-write attempt is a bug or an attack, and both should be loud.
--
-- This fires for the table OWNER too, deliberately. A genuine correction — a
-- termination date recorded wrongly — then requires ALTER TABLE ... DISABLE
-- TRIGGER as the migrator: possible, deliberate, and impossible to do by
-- accident, which is the same posture as purging.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION app_baa_acceptance_transition_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.organization_id IS DISTINCT FROM OLD.organization_id
     AND OLD.organization_id IS NOT NULL THEN
    RAISE EXCEPTION
      'baa_acceptance %: already bound to organization %; refusing to move it to %.',
      OLD.id, OLD.organization_id, NEW.organization_id
      USING
        ERRCODE = 'check_violation',
        HINT = 'An agreement belongs to the practice it names. Have that practice sign its own.';
  END IF;

  IF OLD.bound_at IS NOT NULL AND NEW.bound_at IS DISTINCT FROM OLD.bound_at THEN
    RAISE EXCEPTION
      'baa_acceptance %: bound_at is already recorded as %; refusing to change it.',
      OLD.id, OLD.bound_at
      USING ERRCODE = 'check_violation';
  END IF;

  IF OLD.terminated_at IS NOT NULL
     AND NEW.terminated_at IS DISTINCT FROM OLD.terminated_at THEN
    RAISE EXCEPTION
      'baa_acceptance %: terminated_at is already recorded as %; refusing to change it to %.',
      OLD.id, OLD.terminated_at, NEW.terminated_at
      USING
        ERRCODE = 'check_violation',
        HINT = 'This date is the retention clock (45 CFR 164.530(j)(2)). Correcting it is a deliberate act: ALTER TABLE baa_acceptances DISABLE TRIGGER baa_acceptances_transition_guard, as the owner, with a reason.';
  END IF;

  IF OLD.copy_sent_at IS NOT NULL
     AND NEW.copy_sent_at IS DISTINCT FROM OLD.copy_sent_at THEN
    RAISE EXCEPTION
      'baa_acceptance %: a copy was already recorded as sent at %; refusing to overwrite that.',
      OLD.id, OLD.copy_sent_at
      USING
        ERRCODE = 'check_violation',
        HINT = 'The first delivery is the fact that matters. A later, different document is a separate event and does not belong in this row.';
  END IF;

  IF OLD.copy_document_sha256 IS NOT NULL
     AND NEW.copy_document_sha256 IS DISTINCT FROM OLD.copy_document_sha256 THEN
    RAISE EXCEPTION
      'baa_acceptance %: the delivered document hash is already recorded; refusing to overwrite it.',
      OLD.id
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;
--> statement-breakpoint

COMMENT ON FUNCTION app_baa_acceptance_transition_guard() IS
  'Binding is one-way; terminated_at, copy_sent_at and copy_document_sha256 are write-once. Enforced for every role including the owner, because these are the transitions that move a retention clock or move a contract between practices.';
--> statement-breakpoint

CREATE TRIGGER baa_acceptances_transition_guard
  BEFORE UPDATE ON baa_acceptances
  FOR EACH ROW EXECUTE FUNCTION app_baa_acceptance_transition_guard();
--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- Row-level security: why this table still has none.
--
-- The audit's second finding was that baa_acceptances has no RLS. It still
-- does not, and the honest reason is that RLS cannot express anything true
-- about this table:
--
--   1. It has no clinic_id. Every policy in this database keys on
--      app_current_clinic_id(), and tests/rls-drift.test.ts requires every
--      policy in the schema to do so. A policy here could only reference the
--      tenant decoratively — a predicate written to satisfy a grep is worse
--      than no predicate, because the next reader believes it.
--
--   2. The one moment a tenant IS declared is the moment a policy could not
--      survive. src/lib/provisioning.ts sets app.clinic_id, then calls
--      bindAgreement, and only THEN inserts the clinics row — so at bind time
--      there is no clinics row to resolve the tenant to an organization, and
--      any org-scoped policy denies the legitimate bind. bindAgreement also
--      uses RETURNING, which Postgres checks against the SELECT policy, so
--      even a write-only policy would break it.
--
--   3. Every other path — signing, "download what I signed", the ops listing,
--      lib/agreements/retention.ts — runs on the identity plane with no tenant
--      set at all, exactly like security_events (see 0003). A tenant-keyed
--      predicate has nothing to discriminate on and would have to end in
--      `OR app_current_clinic_id() IS NULL`: an escape hatch that every one of
--      those paths, and anything impersonating them, walks straight through.
--
-- The exploit the audit actually described — one session rebinding another
-- organization's acceptance — is closed above, at the transition level rather
-- than the visibility level, and closed for every role rather than for tenant
-- sessions only. What remains open, stated plainly so nobody mistakes this for
-- a solved problem: anything running as healdesk_app can still READ every row
-- of this table from any session. The table holds contract text and the
-- signer's business contact details, not PHI. Restricting reads would break the
-- buyer's own copy of their agreement, which is the point of the feature this
-- migration supports.
-- ---------------------------------------------------------------------------

-- The posture, asserted rather than described. If a future default-privileges
-- change, a hand-run GRANT, or a role swap widens this table, the migration
-- that follows it fails here instead of shipping a legal record the application
-- can edit.
DO $$
DECLARE
  writable text;
BEGIN
  IF has_table_privilege('healdesk_app'::name, 'baa_acceptances'::regclass, 'DELETE') THEN
    RAISE EXCEPTION
      'healdesk_app holds DELETE on baa_acceptances. This table is append-only (0006); nothing may destroy a signed agreement on a schedule.';
  END IF;

  SELECT string_agg(a.attname, ', ' ORDER BY a.attname)
    INTO writable
    FROM pg_attribute a
   WHERE a.attrelid = 'baa_acceptances'::regclass
     AND a.attnum > 0
     AND NOT a.attisdropped
     AND a.attgenerated = ''
     AND a.attname NOT IN (
           'organization_id', 'bound_at',
           'terminated_at', 'copy_sent_at', 'copy_document_sha256'
         )
     AND has_column_privilege('healdesk_app'::name, a.attrelid, a.attnum, 'UPDATE');

  IF writable IS NOT NULL THEN
    RAISE EXCEPTION
      'healdesk_app can UPDATE evidential column(s) on baa_acceptances: %. Only the binding and retention columns may be writable.',
      writable;
  END IF;
END;
$$;
